package ArraysCollections.Collections;

public class CollectionsTheory {

    // Ao contrario dos arrays, as collections tem tamanho variavel, ou seja, podem crescer com o tempo.
    // Podem ter conteudos de tipos variaveis, apesar de a boa pratica dizer que devem ser usados dados do mesmo tipo.
    // Nao aceita tipos primitivos, somente wrapers.

    // Set (conjunto):
        //  Pode ser ordenado, nao indexado e nao aceita repeticao/objetos duplicados (ou seja, nao aceita dois elementos iguais no mesmo set).
        // Pode ser heterogeneo (forma nao ideal) ou homogeneo (ideal), ou seja, o ideal e usar um conjunto para tipo que necessita ser trabalhado.

    // List (listas):
        // Conjunto indexado (consegue acessar os itens atraves de sua posicao, a partir do 0) e que aceita repeticao.

    // Map:
        // Estrutura chave valor (como se fossem duas colunas), a chave nao aceita repeticao, mas o valor aceita repeticao.

    // Queue:
        // Implementa uma fila com a logica FIFO (first in/first out).

    // Stack (pilha):
        // Implementa uma pilha com a logica LIFO (last in/first out).
}
